use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

// `super::` rather than `crate::`: the integration tests compile this module beside its own copies
// of `ffi_surface` and `parse`, as they do for the other self-contained bindgen modules.
use super::ffi_surface::{FfiSignature, FfiSurface};
use super::parse::{
    CrateExports, ParsedFn, ReturnKind, classify_return, to_camel_case, to_pascal_case,
};

// Owned byte results. flight-ffi returns a `Box<[u8]>` / `Vec<u8>` (TypeScript `Uint8Array`) as an
// owned handle read through three generated companions of the producing function `f`:
// `f_result_len(handle) -> size_t`, `f_result_get(handle, index) -> void *` (a pointer to one
// `uint8_t`, null when the handle is null or the index is out of range) and `f_result_free(handle)`
// (a null handle is a no-op). The C ABI is unchanged here: each native target wraps the handle in
// one generated `ByteResult` base type, specialized per producer in the producer's own `_fn`
// module so it reads and frees through that producer's triple, exactly once. JavaScript binds the
// TypeScript SDK, whose result already is a `Uint8Array`; its `ByteResult` is that array.

/// The outcome of checking every exported byte producer against the native surfaces: the bound
/// producer symbols in sorted order, and every violation that must refuse generation.
#[derive(Clone, Debug, PartialEq)]
pub struct ByteResultTriples {
    pub bound: Vec<String>,
    pub errors: Vec<String>,
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum NativeByteTarget {
    Cpp,
    Hl,
}

/// The three native externs of `func`'s result triple, emitted into the same `_fn` extern class as
/// `func` itself.
pub fn byte_result_accessor_externs(func: &ParsedFn, target: NativeByteTarget) -> String {
    let symbol = format!("flight_{}", func.name);
    let len_name = to_camel_case(&format!("{}_result_len", func.name));
    let get_name = to_camel_case(&format!("{}_result_get", func.name));
    let free_name = to_camel_case(&format!("{}_result_free", func.name));
    let (handle, annotation): (&str, fn(&str) -> String) = match target {
        NativeByteTarget::Hl => ("hl.Bytes", |s| format!("@:hlNative(\"flight\", \"{s}\")")),
        NativeByteTarget::Cpp => ("cpp.Star<cpp.Void>", |s| format!("@:native(\"{s}\")")),
    };
    return format!(
        "\t{}\n\tpublic static function {len_name}(result:{handle}):Int;\n\
         \t{}\n\tpublic static function {get_name}(result:{handle}, index:Int):{handle};\n\
         \t{}\n\tpublic static function {free_name}(result:{handle}):Void;",
        annotation(&format!("{symbol}_result_len")),
        annotation(&format!("{symbol}_result_get")),
        annotation(&format!("{symbol}_result_free")),
    );
}

/// The `ByteResult` source each target's `flight._<target>` package receives. On HashLink and
/// hxcpp it is a base class; per-producer subclasses supply the native read and free.
pub fn byte_result_base_source(package: &str) -> String {
    if package == "flight._js" {
        return format!(
            "package {package};\n\n\
/** Generated by flight-bindgen. A byte result of the TypeScript SDK, which is a `Uint8Array` at
\truntime and converts to and from one implicitly. `free` does nothing: JavaScript memory is
\tgarbage-collected. */
abstract {BYTE_RESULT_TYPE}(js.lib.Uint8Array) from js.lib.Uint8Array to js.lib.Uint8Array {{
\tpublic var length(get, never):Int;

\tinline function get_length():Int {{
\t\treturn this.length;
\t}}

\tpublic inline function free():Void {{}}

\tpublic inline function get(index:Int):Int {{
\t\tif (index < 0 || index >= this.length) throw new haxe.Exception('{BYTE_RESULT_TYPE} index $index is outside 0...${{this.length}}');
\t\treturn this[index];
\t}}

\tpublic inline function toBytes():haxe.io.Bytes {{
\t\treturn haxe.io.Bytes.ofData(this.buffer.slice(this.byteOffset, this.byteOffset + this.byteLength));
\t}}
}}
"
        );
    }
    return format!(
        "package {package};\n\n\
/** Generated by flight-bindgen. An owned byte result of a flight-ffi function. The caller owns it
\tand releases it with `free`, which calls the producing function's `_result_free` exactly once;
\tlater calls do nothing. A null native handle (an absent or empty result) reads as zero bytes.
\t`get` and `toBytes` read through the producer's `_result_get` while the result is alive. */
class {BYTE_RESULT_TYPE} {{
\tpublic var length(default, null):Int;

\tvar isFreed:Bool;

\tfunction new(length:Int) {{
\t\tthis.length = length;
\t\tthis.isFreed = false;
\t}}

\tpublic final function free():Void {{
\t\tif (isFreed) return;
\t\tisFreed = true;
\t\tlength = 0;
\t\tfreeNative();
\t}}

\tpublic final function get(index:Int):Int {{
\t\tif (index < 0 || index >= length) throw new haxe.Exception('{BYTE_RESULT_TYPE} index $index is outside 0...$length');
\t\treturn readNative(index);
\t}}

\tpublic final function toBytes():haxe.io.Bytes {{
\t\tif (isFreed) throw new haxe.Exception('{BYTE_RESULT_TYPE} has been freed');
\t\tvar bytes = haxe.io.Bytes.alloc(length);
\t\tfor (index in 0...length) bytes.set(index, readNative(index));
\t\treturn bytes;
\t}}

\tfunction freeNative():Void {{}}

\tfunction readNative(index:Int):Int {{
\t\treturn 0;
\t}}
}}
"
    );
}

/// The `return` statement that hands a producer's raw handle (`call`, a complete expression) to
/// its `ByteResult` subclass. An optional producer returns null for a null handle.
pub fn byte_result_return(
    package: &str,
    module: &str,
    func: &ParsedFn,
    call: &str,
    optional: bool,
) -> String {
    let subclass = format!("{package}._fn.{module}.{}", byte_result_subclass_name(func));
    if optional {
        return format!("return {subclass}.wrapOptional({call});");
    }
    return format!("return new {subclass}({call});");
}

fn byte_result_subclass_name(func: &ParsedFn) -> String {
    return format!("{}ByteResult", to_pascal_case(&func.name));
}

fn byte_result_subclass_name_for_symbol(symbol: &str) -> String {
    return format!(
        "{}ByteResult",
        to_pascal_case(symbol.strip_prefix("flight_").unwrap_or(symbol))
    );
}

/// The per-producer subclass emitted after the `_fn` extern class `module`, so the producer, its
/// three accessors and the type that frees through them always share one module.
pub fn byte_result_subclass_source(
    func: &ParsedFn,
    module: &str,
    target: NativeByteTarget,
    optional: bool,
) -> String {
    let name = byte_result_subclass_name(func);
    let len_name = to_camel_case(&format!("{}_result_len", func.name));
    let get_name = to_camel_case(&format!("{}_result_get", func.name));
    let free_name = to_camel_case(&format!("{}_result_free", func.name));
    let (package, handle, is_null, read) = match target {
        NativeByteTarget::Hl => (
            "flight._hl",
            "hl.Bytes",
            "handle == null".to_string(),
            format!("{module}.{get_name}(handle, index).getUI8(0)"),
        ),
        // A raw pointer has no Haxe null; compare and dereference it in C++.
        NativeByteTarget::Cpp => (
            "flight._cpp",
            "cpp.Star<cpp.Void>",
            "untyped __cpp__(\"{0} == NULL\", handle)".to_string(),
            format!(
                "untyped __cpp__(\"(int)*(const unsigned char *)({{0}})\", {module}.{get_name}(handle, index))"
            ),
        ),
    };
    let wrap = if optional {
        format!(
            "\tpublic static function wrapOptional(handle:{handle}):Null<{package}.{BYTE_RESULT_TYPE}> {{\n\
             \t\treturn {is_null} ? null : new {name}(handle);\n\
             \t}}\n\n"
        )
    } else {
        String::new()
    };
    return format!(
        "final class {name} extends {package}.{BYTE_RESULT_TYPE} {{\n\
         \tvar handle:{handle};\n\n\
         \tpublic function new(handle:{handle}) {{\n\
         \t\tsuper({module}.{len_name}(handle));\n\
         \t\tthis.handle = handle;\n\
         \t}}\n\n\
         {wrap}\
         \toverride function freeNative():Void {{\n\
         \t\t{module}.{free_name}(handle);\n\
         \t}}\n\n\
         \toverride function readNative(index:Int):Int {{\n\
         \t\treturn {read};\n\
         \t}}\n\
         }}\n"
    );
}

fn check_byte_result_triple(surface: &FfiSurface, symbol: &str) -> Result<(), String> {
    let signature = |ret: &str, params: &[&str]| FfiSignature {
        ret: ret.to_string(),
        params: params.iter().map(|param| param.to_string()).collect(),
    };
    let expected = [
        (
            format!("{symbol}_result_len"),
            signature("size_t", &["void *"]),
            signature("_I32", &["_BYTES"]),
        ),
        (
            format!("{symbol}_result_get"),
            signature("void *", &["void *", "size_t"]),
            signature("_BYTES", &["_BYTES", "_I32"]),
        ),
        (
            format!("{symbol}_result_free"),
            signature("void", &["void *"]),
            signature("_VOID", &["_BYTES"]),
        ),
    ];
    if surface
        .c
        .get(symbol)
        .is_some_and(|producer| producer.ret != "void *")
    {
        return Err(format!(
            "{symbol} does not return a `void *` handle on the C surface"
        ));
    }
    if surface
        .hl
        .get(symbol)
        .is_some_and(|producer| producer.ret != "_BYTES")
    {
        return Err(format!(
            "{symbol} does not return a `_BYTES` handle on the HashLink surface"
        ));
    }
    for (companion, c_expected, hl_expected) in &expected {
        match surface.c.get(companion) {
            None => return Err(format!("{companion} is missing from the C surface")),
            Some(actual) if actual != c_expected => {
                return Err(format!(
                    "{companion} is {actual:?} on the C surface, expected {c_expected:?}"
                ));
            }
            Some(_) => {}
        }
        match surface.hl.get(companion) {
            None => return Err(format!("{companion} is missing from the HashLink surface")),
            Some(actual) if actual != hl_expected => {
                return Err(format!(
                    "{companion} is {actual:?} on the HashLink surface, expected {hl_expected:?}"
                ));
            }
            Some(_) => {}
        }
    }
    return Ok(());
}

fn collect_files(dir: &Path) -> Vec<std::path::PathBuf> {
    let mut out: Vec<_> = fs::read_dir(dir)
        .unwrap()
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "hx"))
        .collect();
    out.sort();
    return out;
}

/// Checks that every exported function bindgen types as a byte result has an exact result triple
/// on both native surfaces. A missing or drifted companion, a byte result that is a native skip, or
/// an SDK type that would collide with the generated `ByteResult` is an error; any error refuses
/// generation.
pub fn enforce_byte_result_triples(
    exports: &[CrateExports],
    surface: &FfiSurface,
) -> ByteResultTriples {
    let mut errors = Vec::new();
    let mut bound = Vec::new();
    for crate_export in exports {
        for parsed in &crate_export.structs {
            if parsed.name == BYTE_RESULT_TYPE {
                errors.push(format!(
                    "{} defines a type named {BYTE_RESULT_TYPE}, which the generated byte result owns",
                    crate_export.dir_name
                ));
            }
        }
        for func in &crate_export.fns {
            let symbol = format!("flight_{}", func.name);
            if !surface.c.contains_key(&symbol) {
                continue;
            }
            if get_byte_result_optional(func).is_none() {
                continue;
            }
            if surface.native_skips.contains(&symbol) {
                errors.push(format!("{symbol} returns owned bytes but is a native skip"));
                continue;
            }
            match check_byte_result_triple(surface, &symbol) {
                Ok(()) => bound.push(symbol),
                Err(reason) => errors.push(format!("{symbol} returns owned bytes but {reason}")),
            }
        }
    }
    bound.sort();
    bound.dedup();
    return ByteResultTriples { bound, errors };
}

/// `Some(optional)` when `func` returns owned bytes bindgen types as a `ByteResult`: a `u8` boxed
/// slice or vector, with `optional` true for the `Option` form.
pub fn get_byte_result_optional(func: &ParsedFn) -> Option<bool> {
    return match classify_return(func.ret.as_deref()?)? {
        ReturnKind::BoxSliceReturn(element) | ReturnKind::VecReturn(element) if element == "u8" => {
            Some(false)
        }
        ReturnKind::OptionBoxSliceReturn(element) | ReturnKind::OptionVecReturn(element)
            if element == "u8" =>
        {
            Some(true)
        }
        _ => None,
    };
}

/// True when any exported function returns owned bytes, so the `ByteResult` types are needed.
pub fn has_byte_results(exports: &[CrateExports]) -> bool {
    return exports
        .iter()
        .flat_map(|crate_export| &crate_export.fns)
        .any(|func| get_byte_result_optional(func).is_some());
}

fn native_symbols(content: &str, backend: &str) -> BTreeSet<String> {
    return content
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            let rest = if backend == "_hl" {
                line.strip_prefix("@:hlNative(\"flight\", \"")
            } else {
                line.strip_prefix("@:native(\"")
            }?;
            return rest.split('"').next().map(str::to_string);
        })
        .collect();
}

/// Checks the generated tree: each bound producer is declared by exactly one `_fn` module per
/// generated native backend, together with its three accessors and its `ByteResult` subclass; no
/// accessor sits in a module without its producer; and no facade function returns `Dynamic` for a
/// byte result.
pub fn verify_byte_result_modules(out_dir: &Path, bound: &[String]) -> Vec<String> {
    let mut errors = Vec::new();
    for backend in ["_hl", "_cpp"] {
        let dir = out_dir.join("flight").join(backend).join("_fn");
        if !dir.is_dir() {
            continue;
        }
        let mut producer_files: BTreeMap<&str, Vec<String>> = BTreeMap::new();
        for path in collect_files(&dir) {
            let file = path.file_name().unwrap().to_string_lossy().to_string();
            let content = fs::read_to_string(&path).unwrap();
            let symbols = native_symbols(&content, backend);
            for symbol in bound {
                let companions = ["_result_len", "_result_get", "_result_free"]
                    .map(|suffix| format!("{symbol}{suffix}"));
                let has_producer = symbols.contains(symbol.as_str());
                for companion in &companions {
                    let has_companion = symbols.contains(companion.as_str());
                    if has_producer && !has_companion {
                        errors.push(format!("{backend}/_fn/{file}: {symbol} omits {companion}"));
                    }
                    if has_companion && !has_producer {
                        errors.push(format!(
                            "{backend}/_fn/{file}: {companion} is generated outside the module of {symbol}"
                        ));
                    }
                }
                if has_producer {
                    producer_files
                        .entry(symbol.as_str())
                        .or_default()
                        .push(file.clone());
                    let subclass = format!(
                        "final class {} extends flight.{backend}.{BYTE_RESULT_TYPE} {{",
                        byte_result_subclass_name_for_symbol(symbol)
                    );
                    if !content.contains(&subclass) {
                        errors.push(format!(
                            "{backend}/_fn/{file}: {symbol} has no {BYTE_RESULT_TYPE} subclass"
                        ));
                    }
                }
            }
        }
        for symbol in bound {
            let count = producer_files.get(symbol.as_str()).map_or(0, Vec::len);
            if count != 1 {
                errors.push(format!(
                    "{backend}: {symbol} is declared by {count} _fn modules, expected exactly 1"
                ));
            }
        }
    }
    let facade_dir = out_dir.join("flight");
    if facade_dir.is_dir() {
        let names: BTreeSet<String> = bound
            .iter()
            .map(|symbol| to_camel_case(symbol.strip_prefix("flight_").unwrap()))
            .collect();
        for path in collect_files(&facade_dir) {
            let file = path.file_name().unwrap().to_string_lossy().to_string();
            for line in fs::read_to_string(&path).unwrap().lines() {
                let Some(rest) = line.strip_prefix("extern inline function ") else {
                    continue;
                };
                let Some(name) = rest.split('(').next() else {
                    continue;
                };
                if !names.contains(name) {
                    continue;
                }
                let ret = rest.rsplit_once("):").map(|(_, ret)| ret).unwrap_or("");
                if !ret.contains(BYTE_RESULT_TYPE) {
                    errors.push(format!(
                        "{file}: {name} returns {} instead of {BYTE_RESULT_TYPE}",
                        ret.trim_end_matches(" {").trim()
                    ));
                }
            }
        }
    }
    return errors;
}

pub const BYTE_RESULT_TYPE: &str = "ByteResult";
