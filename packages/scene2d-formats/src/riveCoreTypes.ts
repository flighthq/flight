/**
 * Rive's core type registry: the name behind every object type key, and the inheritance each type
 * declares. A `.riv` identifies objects only by number, and behaviour is inherited — a Rectangle is
 * a Shape is a Node is a Component — so a reader that tests type keys for equality misses every
 * subclass. `isRiveCoreTypeDerivedFrom` is what lets a stage ask the question it actually means.
 *
 * Derived from the 368 object-model definitions the format publishes as data. Every type key is
 * unique, every declared parent resolves, and the inheritance graph is acyclic and at most eight
 * deep, all of which this table's own test re-checks.
 */

/** The type's name, or undefined for a key this object model does not define. */
export function getRiveCoreTypeName(typeKey: number): string | undefined {
  return _typesByKey.get(typeKey)?.name;
}

/**
 * Whether `typeKey` is `ancestorTypeKey` or inherits from it. A type is derived from itself, so this
 * reads as the "is a" test a caller means: a Rectangle is a Shape, and a Shape is a Shape.
 */
export function isRiveCoreTypeDerivedFrom(typeKey: number, ancestorTypeKey: number): boolean {
  let current: number | undefined = typeKey;
  while (current !== undefined && current !== RIVE_NO_PARENT) {
    if (current === ancestorTypeKey) return true;
    current = _typesByKey.get(current)?.parent;
  }
  return false;
}

