// Pins two anchors together and confines relative rotation to the frame's X axis — a door, a wheel
// bearing, an elbow. Optionally motorized and angle-limited.
//
// `lowerAngle` and `upperAngle` are RADIANS, like every angle in the math layer, measured from frame A's Y
// axis to frame B's Y axis about the shared X axis, so the interval is signed and may straddle zero. The
// motor drives the relative angular velocity about that axis toward `motorSpeed`, spending at most
// `maxMotorTorque`; limits are solved after it and may override it, because a limit is a hard bound and a
// motor is a request.
export interface Physics3DHingeJoint extends Physics3DJoint, Physics3DJointFrames {
  enableLimit: boolean;
  lowerAngle: number;
  upperAngle: number;

  enableMotor: boolean;
  motorSpeed: number;
  maxMotorTorque: number;
  // The motor's own accumulator. It is kind-specific rather than part of the `impulse0..5` block because
  // the block's six slots are spoken for by the point and angular rows, and because a motor impulse is
  // scaled and cleared on its own schedule — see `scaleAccumulatedImpulses`.
  motorImpulse: number;

  // The two limit rows' accumulators, carried across steps so a limit under sustained load warm-starts
  // like every other constraint. Without them a hinge resting against its stop re-converges from zero
  // every step, and a loaded stop sags and buzzes at the exact pose it is meant to hold still.
  //
  // Non-negative MAGNITUDES, not signed coordinates: a one-sided row may only push, so each is clamped at
  // zero and its direction is carried by which row owns it. That is why `swapEnds` exchanges the two
  // without negating either, while the BOUNDS it exchanges are negated — bounds are positions on an axis
  // that reverses, these are pushes that do not.
  // A COMPLIANT limit: once the bound is crossed, the stop pushes back like a spring of
  // `limitFrequencyHz` and `limitDampingRatio` instead of arresting the coordinate outright. What a
  // ragdoll wants at the end of a joint's range and a suspension wants at the end of its travel.
  //
  // The stop stays ONE-SIDED whichever it is: softening changes how hard the row resists being crossed,
  // never whether it may pull the coordinate back the other way. A spring that could pull would be a
  // rest length, which is the distance joint's job.
  //
  // Both parameters are ignored unless `enableLimitSpring` is true and the frequency is positive, so a
  // joint that never sets them behaves exactly as a hard stop.
  enableLimitSpring: boolean;
  limitFrequencyHz: number;
  limitDampingRatio: number;
  lowerLimitImpulse: number;
  upperLimitImpulse: number;
}

