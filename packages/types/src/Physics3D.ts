// The behaviour of one joint kind. Registered per world by kind, so two worlds in one process can carry
// different custom joints without one seeing the other's.
//
// `prepare` runs once per substep, before iteration, and rebuilds whatever the kind derives from the
// current poses. `solve` runs once per velocity iteration and applies its impulses IMMEDIATELY, because
// that is what makes a sequential solver converge.
//
// `solve` TAKES `dt`, unlike the 2D package's, whose `solve(world, joint)` is velocity-level by
// construction. The parameter is what keeps a position-based or compliant solver registerable: such a
// solver's multiplier update divides its compliance by `dt` squared, so a signature without `dt` closes
// the registry to every solver that is not velocity-level. It costs one argument now and cannot be
// added later without breaking every registered kind.
//
// Neither may add or remove bodies, contacts, or joints: the solve list is fixed for the step.
export interface Physics3DJointSolver {
  prepare(world: Physics3DWorld, joint: Physics3DJoint, dt: number): void;
  solve(world: Physics3DWorld, joint: Physics3DJoint, dt: number): void;
  // Whether bodyA participates in this kind's constraint. Omit for the ordinary two-body case. A
  // one-body kind sets false so world services do not resolve, wake, remove, island-connect, or
  // suppress collisions through a placeholder endpoint the solver never reads.
  usesBodyA?: boolean;
  // Whether this constraint represents continuing external control and therefore keeps its
  // participating non-static bodies awake.
  keepsBodiesAwake?: boolean;
  // Whether this kind's two ends may be exchanged, and its chance to carry direction-bearing state
  // across the exchange. Called with the ends still in their original order; return true to let the
  // generic swap of bodies and anchors proceed, false to veto it. The generic swap can only move what
  // every joint has — two body indices and two anchors — and anything a kind measures FROM bodyA TO
  // bodyB reverses sign when the ends trade places.
  swapEnds?(joint: Physics3DJoint): boolean;
  // Writes the force and torque this kind's rows applied over the sub-interval just solved, in world
  // space at the anchor, and returns whether it could. Reading the `impulse0..5` block generically is not
  // an option: the slots mean different things per kind — three world axes for a point block, one axial
  // scalar for a distance joint — so only the kind that wrote them can say what they add up to.
  //
  // Omit it and the kind reports no reaction, `writePhysics3DJointReaction` returns false for it, and it
  // never breaks. That is the honest reading of a kind that cannot measure its own load.
  writeReaction?(joint: Readonly<Physics3DJoint>, inverseDt: number, out: Physics3DJointReaction): boolean;
  // Reapplies the impulses this joint converged on last substep, before iteration begins. Called after
  // `prepare`, so the current lever arms are in place. Omit it and the kind starts each substep cold,
  // which is correct but converges more slowly.
  warmStart?(world: Physics3DWorld, joint: Physics3DJoint): void;
  // Scales kind-specific accumulators when the caller changes timestep. The common `impulse0..5` block
  // is scaled by the step itself; a motor or another extra accumulator belongs here.
  scaleAccumulatedImpulses?(joint: Physics3DJoint, timestepRatio: number): void;
  // Discards the accumulated impulses, so a world with warm starting switched off does not keep seeding
  // each substep from a cache it has been told not to use.
  clearAccumulatedImpulses?(joint: Physics3DJoint): void;
}

// The ORIENTATION half of a joint's two attachment frames. `Physics3DJoint` carries the position half —
// the two local anchors — and a kind that constrains only a point needs nothing more. Every other kind
// needs a full frame, and this is that frame's rotation: one unit quaternion per body, taking the joint's
// own axes into that body's local frame.
//
// One convention holds across every kind that has an axis: THE JOINT'S PRIMARY AXIS IS THE FRAME'S LOCAL
// +X. A hinge spins about frame X, a slider translates along frame X, a cone-twist twists about frame X
// and swings X away from X, and a 6-DOF numbers its axes X, Y, Z in that frame. Frame Y and Z are the
// perpendicular pair a hinge measures its angle against and a cone-twist's two swing limits are named for.
//
// Fixing ONE axis for every kind is the whole point. Engines that let each joint choose (a hinge about Z,
// a cone-twist about X) make the convention a per-kind fact a reader has to carry, and a frame authored
// for one kind then means something else in another. Here a frame is a frame.
export interface Physics3DJointFrames {
  localRotationAX: number;
  localRotationAY: number;
  localRotationAZ: number;
  localRotationAW: number;
  localRotationBX: number;
  localRotationBY: number;
  localRotationBZ: number;
  localRotationBW: number;
}

// The authoring options every joint factory accepts. Anchors and `collideConnected` default, the two body
// indices do not: a joint without endpoints has no meaning to default to.
// The load a joint is carrying: the force and torque the constraint applied over one sub-interval,
// measured at the ANCHOR and expressed in world space.
//
// At the anchor rather than at the centre of mass, which is what makes the two readings independent. A
// linear constraint row acting through an offset anchor exerts `r x F` about the centre, so a torque
// measured there would rise with pure hanging load and a `breakTorque` would fire on weight alone.
//
// A FORCE, not an impulse: the solver accumulates impulses, and dividing by the sub-interval turns a
// quantity that changes with timestep into one that does not.
export interface Physics3DJointReaction {
  forceX: number;
  forceY: number;
  forceZ: number;
  torqueX: number;
  torqueY: number;
  torqueZ: number;
}

