  // The broadphase. The BACKEND rather than a `SpatialIndex3D`, matching `Physics2DWorld` exactly: the
  // world drives it directly, so a caller may hand over a grid, a tree, or its own implementation of the
  // seam without this package knowing which.
  index: SpatialIndexBackend3D;

  contacts: Physics3DContact[];
  joints: Physics3DJoint[];
  jointSolvers: Map<Physics3DJointKind, Physics3DJointSolver>;
  // Active two-body joints with `collideConnected=false`, indexed by canonical body pair. The nested
