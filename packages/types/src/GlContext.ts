// These options affect only WebGL context acquisition. Keeping them separate from GlRenderOptions
// prevents callers that already own a context from supplying fields createGlRenderState cannot use.
export interface GlContextOptions {
  readonly antialias?: boolean;
  readonly contextAttributes?: WebGLContextAttributes;
  readonly powerPreference?: WebGLPowerPreference;
}
